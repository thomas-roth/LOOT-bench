"""Variant definitions for the object-insertion task category.

Three kinds of task share one command/observation/reward stack:

- ``peg``        a single peg must be inserted into a single tight-fitting bore
                 on a fixed board. The bore is either vertical (mouth up) or
                 horizontal (mouth facing the robot).
- ``two_sheet``  a peg must be inserted through a hole that only lines up once
                 a movable top sheet has been slid over the fixed bottom sheet.
- ``sorter``     a free-standing shape-sorter cube (one shaped hole per face)
                 plus one piece per socket. The cube spawns at a random flat
                 orientation, so the robot may first have to reorient it; a
                 single commanded piece must be pushed through its matching hole,
                 the other pieces are distractors.

Geometry conventions (all lengths in metres):

- For ``peg``/``two_sheet``, a *shape* is a convex prism. ``circle`` is a
  cylinder, ``square``/``rect`` are boxes, ``triangle``/``hexagon`` are
  regular-polygon prisms built as the convex hull of their corner vertices.
  ``circumradius``/``nsides`` fully describe the cross section; the matching
  bore is a polygonal ring with apothem
  ``circumradius*cos(pi/nsides) + clearance`` so the peg is a tight fit.
- For ``sorter``, geometry comes from the committed STL assets and
  ``xmls/sorter_layout.json`` (generated by ``xmls/make_sorter_assets.py``,
  the single source for both the collision geometry and the success metric);
  ``SHAPE_GEOMS`` and the ``bore_depth``/``insert_depth``/``lateral_tol``/
  ``tilt_tol_deg`` fields below are ignored. ``star`` exists only there.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Literal, cast

Shape = Literal["circle", "square", "rect", "triangle", "hexagon", "star"]
Orientation = Literal["vertical", "horizontal"]
Kind = Literal["peg", "two_sheet", "sorter"]

# Peg length along its insertion axis (total height = 2 * PEG_HALF_LEN).
PEG_HALF_LEN = 0.03
# Radial gap between a peg and its bore wall (tight fit).
CLEARANCE = 0.0015


@dataclass(frozen=True)
class ShapeGeom:
    """Cross-section description shared by a peg and its matching bore."""

    nsides: int
    """Number of polygon sides; ``circle`` uses a smooth bore (>=16)."""
    circumradius: float
    """Distance from the cross-section centre to a corner."""
    rect_half: tuple[float, float] | None = None
    """For ``rect`` only: (half-x, half-y) of the rectangular cross section."""

    @property
    def inradius(self) -> float:
        """Centre-to-edge distance (apothem) of the peg cross section."""
        if self.rect_half is not None:
            return min(self.rect_half)
        return self.circumradius * math.cos(math.pi / self.nsides)


# Distinct cross sections, each a tight fit in its own matching bore. Shape
# matching for scoring is enforced by index (peg i is only ever checked
# against socket i, see InsertionCommand), not by physical exclusion -- these
# sizes do NOT guarantee a peg can't physically slide into a neighbouring,
# differently-shaped hole (e.g. the hexagon peg is small enough to enter the
# circle bore). Making that physically impossible for every shape pair needs
# a coordinated resize of all shapes plus the board/tray layout, verified in
# sim; out of scope here.
# Distinct, tightly-sized cross sections for the peg/two_sheet kinds. Sizes
# are chosen so a peg does not drop into a neighbouring hole (different
# circum/inradius signatures).
SHAPE_GEOMS: dict[Shape, ShapeGeom] = {
    "circle": ShapeGeom(nsides=24, circumradius=0.0140),
    "square": ShapeGeom(nsides=4, circumradius=0.0130 * math.sqrt(2.0)),
    "rect": ShapeGeom(nsides=4, circumradius=0.0, rect_half=(0.0210, 0.0105)),
    "triangle": ShapeGeom(nsides=3, circumradius=0.0210),
    "hexagon": ShapeGeom(nsides=6, circumradius=0.0150),
}


def bore_apothem(shape: Shape) -> float:
    """Centre-to-wall distance of the bore that the peg slides into."""
    assert shape in SHAPE_GEOMS, f"'{shape}' only exists in the STL sorter"
    return SHAPE_GEOMS[shape].inradius + CLEARANCE


@dataclass(frozen=True)
class SocketCfg:
    """One bore on a board, plus the peg colour assigned to it."""

    shape: Shape
    color: str
    orientation: Orientation = "vertical"


@dataclass(frozen=True)
class InsertionVariantCfg:
    name: str
    """Variant identifier used in the task id (e.g. "PegCylinder")."""
    kind: Kind
    sockets: tuple[SocketCfg, ...]
    """One per peg; peg ``i`` must go into socket ``i``."""
    distractors: tuple[Shape, ...] = ()
    """Extra pegs (no matching socket) scattered as clutter."""
    bore_depth: float = 0.045
    insert_depth: float = 0.026
    """Required insertion depth (along the bore axis) to count as inserted."""
    lateral_tol: float = 0.010
    """Max lateral offset of the peg from the bore axis when inserted."""
    tilt_tol_deg: float = 20.0
    """Max angle between the peg axis and the bore axis when inserted."""

    @property
    def num_sockets(self) -> int:
        return len(self.sockets)

    @property
    def peg_shapes(self) -> tuple[Shape, ...]:
        socket_shapes = cast("tuple[Shape, ...]", tuple(s.shape for s in self.sockets))
        return socket_shapes + self.distractors

    @property
    def peg_colors(self) -> tuple[str, ...]:
        return tuple(s.color for s in self.sockets) + tuple(
            "gray" for _ in self.distractors
        )

    @property
    def orientation(self) -> Orientation:
        return self.sockets[0].orientation

    def __post_init__(self):
        assert self.num_sockets >= 1
        if self.kind == "two_sheet":
            assert self.num_sockets == 1, "two_sheet uses a single through-hole"
            assert self.orientation == "vertical"


