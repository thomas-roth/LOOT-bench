"""Run the three visual checks and build one page that shows them side by side.

Each check writes its pictures and a small JSON verdict into the output folder;
this script collects them into ``index.html``. See tests/qc/faults-visual/README.md.
"""

from __future__ import annotations

import argparse
import html
import json
import subprocess
import sys
from pathlib import Path

OUT_DIR = Path("out/render/faults-visual")
CHECKS = (
    "fault01_action_reach.py",
    "fault02_ee_pose_signflip.py",
    "fault03_start_pose.py",
)

_PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>QC rebuild - the three faults, before and after</title>
<style>
 body {{ font: 16px/1.6 -apple-system, Segoe UI, Roboto, sans-serif;
        background: #f4f6f8; color: #12181f; margin: 0; padding: 2rem 1.5rem 4rem; }}
 main {{ max-width: 74rem; margin: 0 auto; }}
 h1 {{ font-size: 1.8rem; margin: 0 0 .3rem; }}
 h2 {{ font-size: 1.25rem; margin: 2.5rem 0 .2rem; border-bottom: 1px solid #d3dae2;
       padding-bottom: .4rem; }}
 p.q {{ color: #4d5866; margin: .2rem 0 1rem; }}
 ul {{ background: #fff; border: 1px solid #d3dae2; border-left: 3px solid #0d6f78;
       padding: .9rem 1.2rem .9rem 2.4rem; }}
 img {{ width: 100%; border: 1px solid #d3dae2; background: #fff; margin: .6rem 0; }}
 footer {{ color: #77828f; font-size: .85rem; margin-top: 3rem; }}
 code {{ font-family: ui-monospace, Menlo, monospace; font-size: .9em; }}
</style></head><body><main>
<h1>The three faults, before and after</h1>
 <p class="q">Generated by <code>tests/qc/faults-visual/run_all.py</code>. Every number is
measured on this machine, from the current code and the two recorded sessions.</p>
{sections}
<footer>Written to {out}. Regenerate with
<code>uv run python tests/qc/faults-visual/run_all.py</code>.</footer>
</main></body></html>
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cpu", action="store_true")
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    parser.add_argument("--no-render", action="store_true")
    args = parser.parse_args()

    extra = (["--cpu"] if args.cpu else []) + (
        ["--no-render"] if args.no_render else []
    )
    here = Path(__file__).resolve().parent
    for check in CHECKS:
        print(f"== {check}")
        result = subprocess.run(
            [sys.executable, str(here / check), "--out", str(args.out), *extra],
            check=False,
        )
        if result.returncode != 0:
            sys.exit(f"{check} failed with exit code {result.returncode}")

    sections = []
    for verdict in sorted(args.out.glob("fault*.json")):
        payload = json.loads(verdict.read_text())
        lines = "".join(f"<li>{html.escape(line)}</li>" for line in payload["lines"])
        pictures = "".join(
            f'<img src="{html.escape(name)}" alt="{html.escape(payload["title"])}">'
            for name in payload["images"]
        )
        sections.append(
            f"<h2>{html.escape(payload['title'])}</h2>"
            f'<p class="q">{html.escape(payload["question"])}</p>'
            f"<ul>{lines}</ul>{pictures}"
        )

    page = args.out / "index.html"
    page.write_text(_PAGE.format(sections="\n".join(sections), out=args.out))
    print()
    print(f"Open {page}")


if __name__ == "__main__":
    main()
